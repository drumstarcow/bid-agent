def now() -> str:
    return datetime.now(CST).strftime('%Y-%m-%d %H:%M:%S')


def today() -> str:
    return datetime.now(CST).strftime('%Y-%m-%d')


def connect(db_path: str | None = None) -> sqlite3.Connection:
    path = db_path or _db_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    conn = sqlite3.connect(path)
    conn.row_factory = sqlite3.Row
    conn.execute('PRAGMA foreign_keys=ON')
    return conn


def initialize(db_path: str | None = None) -> None:
    with connect(db_path) as conn:
        conn.executescript(SCHEMA)


def event(conn: sqlite3.Connection, actor: str, action: str, detail: str) -> None:
    conn.execute('INSERT INTO events(actor,action,detail,created_at) VALUES(?,?,?,?)', (actor, action, detail, now()))


def seed(conn: sqlite3.Connection) -> None:
    """空库时播种演示数据；已有数据不重复播种、不重置状态。"""
    if conn.execute('SELECT COUNT(*) c FROM tenders').fetchone()['c'] > 0:
        return
    conn.executemany('INSERT INTO certs VALUES(?,?,?,?,?,?,?,?,?)', CERTS)
    conn.executemany('INSERT INTO cases VALUES(?,?,?,?,?,?,?,?,?)', CASES)
    conn.executemany('INSERT INTO solutions VALUES(?,?,?,?,?,?,?,?)', SOLUTIONS)
    conn.executemany('INSERT INTO quotes VALUES(?,?,?,?,?,?,?)', QUOTES)
    conn.executemany('INSERT INTO tenders VALUES(?,?,?,?,?,?,?,?,?,?,?)', TENDERS)
    conn.executemany('INSERT INTO knowledge VALUES(?,?,?,?,?)', KNOWLEDGE)
    conn.executemany('INSERT INTO prompts VALUES(?,?,?,?)', PROMPTS)
    event(conn, 'system', '初始化演示数据',
          f'播种证照 {len(CERTS)} 项、业绩 {len(CASES)} 个、方案 {len(SOLUTIONS)} 套、报价模型 {len(QUOTES)} 套、标讯 {len(TENDERS)} 条、知识库 {len(KNOWLEDGE)} 条、提示词模板 {len(PROMPTS)} 个')
